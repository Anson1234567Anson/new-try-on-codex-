// Runs the training experiments that the lessons show, and saves the results
// to src/model/experiments.json (plus the 2-head weights for the multi-head lesson).
// Run with: npm run experiments    (takes a few minutes)
import { writeFileSync } from 'node:fs';
import { GPT, Adam, DEFAULT_CONFIG, sgdStep, warmupCosine, type Config } from '../src/model/gpt';
import { NAMES, TRAIN_NAMES, VAL_NAMES, example, rng } from '../src/model/data';
import trained from '../src/model/weights.json';
import { existsSync, readFileSync } from 'node:fs';

// ONLY=overfit,finetune re-runs just those sections and keeps the rest of the saved file.
const ONLY = process.env.ONLY?.split(',');
const want = (k: string) => !ONLY || ONLY.includes(k);
const FILE = new URL('../src/model/experiments.json', import.meta.url);

type Ex = { x: number[]; y: number[] };
const TRAIN = TRAIN_NAMES.map(example);
const VAL = VAL_NAMES.map(example);
const r3 = (v: number) => (Number.isFinite(v) ? +v.toFixed(3) : null);

interface RunOpts {
  cfg?: Partial<Config>; steps: number; batch?: number; every?: number;
  opt?: 'adam' | 'sgd'; lr: number | ((step: number) => number); data?: Ex[]; val?: Ex[];
  seed?: number; model?: GPT; samplesAt?: number[]; log?: boolean;
  /** extra measurement recorded at every log point */
  extra?: (m: GPT) => unknown;
}
interface RunLog { every: number; train: (number | null)[]; val: (number | null)[]; lr: number[]; gradNorm: number[]; samples: Record<string, string[]>; seconds: number; extra?: unknown[] }

const writeNames = (m: GPT, n = 8) => { const r = rng(5); return Array.from({ length: n }, () => m.sample(r) || '·'); };

function run(o: RunOpts): { model: GPT; log: RunLog } {
  const model = o.model ?? new GPT({ ...DEFAULT_CONFIG, ...o.cfg }, rng(o.seed ?? 1));
  const data = o.data ?? TRAIN, val = o.val ?? VAL, batch = o.batch ?? 32, every = o.every ?? 25;
  const rand = rng((o.seed ?? 1) + 1);
  const adam = new Adam(model);
  const lrAt = (s: number) => (typeof o.lr === 'number' ? o.lr : o.lr(s));
  const log: RunLog = { every, train: [r3(model.loss(data))], val: [r3(model.loss(val))], lr: [lrAt(0)], gradNorm: [], samples: {}, seconds: 0 };
  if (o.samplesAt?.includes(0)) log.samples[0] = writeNames(model);
  if (o.extra) log.extra = [o.extra(model)];
  const t0 = Date.now();
  let acc = 0, gacc = 0;
  for (let s = 1; s <= o.steps; s++) {
    const b = Array.from({ length: batch }, () => data[Math.floor(rand() * data.length)]);
    acc += model.loss(b, true);
    gacc += model.gradNorm();
    if ((o.opt ?? 'adam') === 'adam') { adam.lr = lrAt(s - 1); adam.step(); } else sgdStep(model, lrAt(s - 1));
    if (s % every === 0) {
      log.train.push(r3(acc / every)); log.gradNorm.push(r3(gacc / every)!); acc = 0; gacc = 0;
      log.val.push(r3(model.loss(val))); log.lr.push(+lrAt(s).toPrecision(3));
      if (o.extra) log.extra!.push(o.extra(model));
    }
    if (o.samplesAt?.includes(s)) log.samples[s] = writeNames(model);
  }
  log.seconds = +((Date.now() - t0) / 1000).toFixed(1);
  if (o.log !== false) console.log(`  ${o.steps} steps · val ${log.val[log.val.length - 1]} · ${log.seconds}s`);
  return { model, log };
}

const out: Record<string, unknown> = ONLY && existsSync(FILE) ? JSON.parse(readFileSync(FILE, 'utf8')) : {};
Object.assign(out, {
  note: 'Generated by scripts/experiments.ts. Every number here comes from really training the course model.',
  split: { train: TRAIN_NAMES.length, val: VAL_NAMES.length, valNames: VAL_NAMES },
});

if (want('optimizers')) {
console.log('optimizers');
out.optimizers = {
  sgd: run({ steps: 1500, opt: 'sgd', lr: 0.5 }).log,
  adam: run({ steps: 1500, opt: 'adam', lr: 0.01 }).log,
};
}

if (want('schedules')) {
console.log('learning-rate schedules');
const S = 2000;
out.schedules = {
  steps: S,
  low: run({ steps: S, lr: 0.003 }).log,
  high: run({ steps: S, lr: 0.05 }).log,
  warmupCosine: run({ steps: S, lr: (s) => warmupCosine(s, S, 0.05, 200) }).log,
};
}

if (want('variants')) {
console.log('architecture variants');
out.variants = {
  steps: 1500,
  base: run({ steps: 1500, lr: 0.01 }).log,
  noPos: run({ steps: 1500, lr: 0.01, cfg: { noPos: true } }).log,
  heads2: run({ steps: 1500, lr: 0.01, cfg: { heads: 2 } }).log,
  layers2: run({ steps: 1500, lr: 0.01, cfg: { layers: 2 } }).log,
  layers2norm: run({ steps: 1500, lr: 0.01, cfg: { layers: 2, norm: true } }).log,
};
}

if (want('overfit')) {
console.log('overfitting');
const SMALL = TRAIN_NAMES.slice(0, 30);
out.overfit = { names: SMALL, ...run({ steps: 1500, lr: 0.01, data: SMALL.map(example), every: 10, samplesAt: [1500], cfg: { hidden: 64 } }).log };
}

if (want('main')) {
console.log('main run (warmup + cosine, 4000 steps)');
const MAIN = 4000;
const main = run({ steps: MAIN, lr: (s) => warmupCosine(s, MAIN, 0.02, 200), every: 50, samplesAt: [0, 100, 250, 500, 1000, 2000, 4000] });
out.main = { steps: MAIN, peakLr: 0.02, warmup: 200, batch: 32, params: main.model.paramCount(), ...main.log };
}

if (want('finetune')) {
console.log('fine-tuning on names that end in "a"');
const ENDS_A = TRAIN_NAMES.filter((n) => n.endsWith('a')).slice(0, 40); // a small fine-tuning set
const VAL_A = VAL_NAMES.filter((n) => n.endsWith('a')).map(example);
const endsA = (m: GPT) => { const r = rng(11); const s = Array.from({ length: 400 }, () => m.sample(r)).filter(Boolean); return +(s.filter((n) => n.endsWith('a')).length / s.length).toFixed(3); };
const base = GPT.fromJSON(trained as never);
const ft = { lr: 0.003, steps: 80 };
const full = run({ model: base.clone(), data: ENDS_A.map(example), val: VAL_A, steps: ft.steps, lr: ft.lr, every: 4, samplesAt: [ft.steps] });
const loraModel = base.clone(); loraModel.addLoRA(['q0', 'k0', 'v0', 'o', 'w1', 'w2', 'u'], 2, rng(3));
const lora = run({ model: loraModel, data: ENDS_A.map(example), val: VAL_A, steps: ft.steps, lr: 0.02, every: 4, samplesAt: [ft.steps] });
const scratch = run({ data: ENDS_A.map(example), val: VAL_A, steps: ft.steps, lr: 0.01, every: 4, samplesAt: [ft.steps] });
out.finetune = {
  task: 'names ending in "a"', trainNames: ENDS_A.length, valNames: VAL_A.length,
  baseSamples: writeNames(base), baseEndsA: endsA(base), baseValLoss: r3(base.loss(VAL_A)),
  full: { ...full.log, trainable: full.model.paramCount(), endsA: endsA(full.model) },
  lora: { ...lora.log, trainable: lora.model.loraCount(), total: lora.model.paramCount(), rank: 2, endsA: endsA(lora.model) },
  scratch: { ...scratch.log, endsA: endsA(scratch.model) },
  allNamesEndsA: +(NAMES.filter((n) => n.endsWith('a')).length / NAMES.length).toFixed(3),
};
}

if (want('moe')) {
  console.log('mixture of experts');
  const STEPS = 1500;
  const lr = (s: number) => warmupCosine(s, STEPS, 0.01, 100);
  // share of held-out tokens (in %) sent to each expert, measured on 200 held-out names
  const usage = (m: GPT) => {
    const c = new Array(m.cfg.experts ?? 0).fill(0); let n = 0;
    for (const ex of VAL.slice(0, 200)) for (const ch of m.forward(ex.x).blocks[0].chosen ?? []) for (const e of ch) { c[e]++; n++; }
    return c.map((v) => +(100 * v / n).toFixed(1));
  };
  const moe = (cfg: Partial<Config>) => run({ steps: STEPS, lr, cfg, extra: cfg.experts ? usage : undefined });
  const dense = moe({});
  const m4 = moe({ experts: 4, balance: 0.01 });
  const noBal = moe({ experts: 4, balance: 0 });
  const top2 = moe({ experts: 4, topK: 2, balance: 0.01 });
  const m8 = moe({ experts: 8, balance: 0.01 });
  out.moe = {
    steps: STEPS, peakLr: 0.01, warmup: 100, batch: 32, usageEvery: 25, usageNames: 200,
    dense: { ...dense.log, params: dense.model.paramCount() },
    experts4: { ...m4.log, params: m4.model.paramCount() },
    noBalance: { ...noBal.log, params: noBal.model.paramCount() },
    top2: { ...top2.log, params: top2.model.paramCount() },
    experts8: { ...m8.log, params: m8.model.paramCount() },
  };
  // the 4-expert model is shipped so lessons can inspect its router
  writeFileSync(new URL('../src/model/weights-moe.json', import.meta.url), JSON.stringify(m4.model.toJSON()));
  writeFileSync(new URL('../src/model/weights-moe-nobalance.json', import.meta.url), JSON.stringify(noBal.model.toJSON()));
}

if (want('heads2')) {
console.log('2-head weights for the multi-head lesson');
const two = run({ steps: 6000, lr: (s) => warmupCosine(s, 6000, 0.01, 200), cfg: { heads: 2 }, data: TRAIN, every: 500 });
writeFileSync(new URL('../src/model/weights-2h.json', import.meta.url), JSON.stringify(two.model.toJSON()));
}

writeFileSync(FILE, JSON.stringify(out));
console.log('saved');
